import type { Flow } from "../model/flows.js";
import { escapeSingleQuoted } from "./escape.js";

const HEADER = `// AI-managed — fully regenerated by likec4-agent sync on every run.
// Do not hand-edit; your changes will be overwritten on the next sync.`;

export function emitFlows(flows: Flow[]): string {
  const blocks = flows
    .filter((flow) => flow.steps.length > 0)
    .map((flow) => {
      const lines = [
        `  dynamic view ${flow.id} {`,
        `    title '${escapeSingleQuoted(flow.title)}'`,
        "",
        ...flow.steps.map(
          (step) =>
            `    ${step.source} -> ${step.target} '${escapeSingleQuoted(step.label)}' // ${step.sourceFile}:${step.sourceLine}`,
        ),
        "  }",
      ];
      return lines.join("\n");
    });

  return `${HEADER}\nviews {\n${blocks.map((b) => `${b}\n`).join("\n")}}\n`;
}
