import type { ParsedElement } from "../types.js";
import { escapeSingleQuoted } from "./escape.js";

const HEADER = `// AI-managed — fully regenerated by likec4-agent sync on every run.
// Do not hand-edit; your changes will be overwritten on the next sync.`;

export function emitElements(elements: ParsedElement[]): string {
  const topLevel = elements.filter((el) => el.parent === undefined);
  const nested = elements.filter((el) => el.parent !== undefined);

  const sortedTopLevel = [...topLevel].sort((a, b) => a.id.localeCompare(b.id));
  const topLevelBlocks = sortedTopLevel.map((el) => elementBlock(el, "  "));

  const groups = new Map<string, ParsedElement[]>();
  for (const el of nested) {
    const parentPath = el.parent as string;
    const group = groups.get(parentPath);
    if (group) {
      group.push(el);
    } else {
      groups.set(parentPath, [el]);
    }
  }

  const extendBlocks = [...groups.keys()].sort().map((parentPath) => {
    const children = [...groups.get(parentPath)!].sort((a, b) => a.id.localeCompare(b.id));
    const childBlocks = children.map((el) => elementBlock(el, "    "));
    return [`  extend ${parentPath} {`, ...childBlocks, "  }"].join("\n");
  });

  const blocks = [...topLevelBlocks, ...extendBlocks];

  return `${HEADER}\nmodel {\n${blocks.map((b) => `${b}\n`).join("\n")}}\n`;
}

function elementBlock(el: ParsedElement, indent: string): string {
  const lines = [`${indent}${el.id} = ${el.kind} '${escapeSingleQuoted(el.title)}' {`];
  if (el.technology) {
    lines.push(`${indent}  technology '${escapeSingleQuoted(el.technology)}'`);
  }
  if (el.description) {
    lines.push(`${indent}  description '${escapeSingleQuoted(el.description)}'`);
  }
  lines.push(`${indent}}`);
  return lines.join("\n");
}
